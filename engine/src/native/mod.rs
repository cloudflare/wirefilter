//! Native field definitions and composable value representations.
//!
//! Native contexts let filters read application-owned Rust values directly. An
//! application can implement the context interfaces on an existing type, or use
//! a small context that borrows its request data and evaluation state.
//!
//! # Context interfaces and state
//!
//! [`EvaluationContext`](crate::EvaluationContext) exposes user data and list
//! matchers, and its [`HasScheme`](crate::HasScheme) supertrait exposes the scheme.
//! These traits do not prescribe storage or define field getters.
//! [`EvaluationContextMut`](crate::EvaluationContextMut) adds mutable access for
//! applications that need to update user data or list matchers.
//!
//! [`NativeContextState`](crate::NativeContextState) is an optional owner of a scheme,
//! list matchers, and user data. It contains no field values. A native context can
//! borrow it and forward the evaluation-context methods to it, while getters read
//! the application's own fields. Applications that already store this state can
//! implement the interfaces directly without using `NativeContextState`.
//!
//! [`ContextFamily`](crate::ContextFamily) associates compiled expressions with
//! the application's context type, including contexts that borrow data. It also
//! binds fields to typed getters during compilation. The
//! [`wirefilter_fields!`](crate::wirefilter_fields) macro generates a family and
//! its field bindings; it does not create a context or store request values.
//! Getters read values when an expression is evaluated.
//!
//! The default [`ExecutionContext`](crate::ExecutionContext) implements the same
//! evaluation interfaces and already owns equivalent state alongside its stored
//! field values. It does not require a separate `NativeContextState`.
//!
//! # Borrowing request data and reusable state
//!
//! This example borrows a request's `Vec<String>` without constructing a
//! Wirefilter array. `RequestFields` is the family generated by the macro;
//! `RequestContext` is the value passed to the compiled filter.
//!
//! ```
//! use wirefilter::{
//!     DefaultCompiler, EvaluationContext, HasScheme, ListMatcher, ListRef, NativeContextState,
//!     Scheme, SchemeBuilder, Type,
//! };
//!
//! struct Request {
//!     names: Vec<String>,
//! }
//!
//! struct RequestContext<'a> {
//!     request: &'a Request,
//!     state: &'a NativeContextState<()>,
//! }
//!
//! impl HasScheme for RequestContext<'_> {
//!     fn scheme(&self) -> &Scheme {
//!         self.state.scheme()
//!     }
//! }
//!
//! impl EvaluationContext for RequestContext<'_> {
//!     type UserData = ();
//!
//!     fn get_user_data(&self) -> &() {
//!         self.state.get_user_data()
//!     }
//!
//!     fn get_list_matcher(&self, list: ListRef<'_>) -> &dyn ListMatcher {
//!         self.state.get_list_matcher(list)
//!     }
//! }
//!
//! wirefilter::wirefilter_fields! {
//!     impl<'data> RequestFields for RequestContext<'data> {
//!         "request.names" => {
//!             fn(ctx: &RequestContext<'data>) -> &[String] {
//!                 &ctx.request.names
//!             }
//!         },
//!     }
//! }
//!
//! # fn main() -> Result<(), Box<dyn std::error::Error>> {
//! let mut builder = SchemeBuilder::new();
//! builder.add_field("request.names", Type::array(Type::Bytes))?;
//! let scheme = builder.build();
//!
//! // Validate every field definition during initialization, before compilation.
//! RequestFields::validate_scheme(&scheme)?;
//! let mut compiler = DefaultCompiler::<(), RequestFields>::new();
//! let filter = scheme
//!     .parse(r#"any(request.names[*] eq "example")"#)?
//!     .compile_with_compiler(&mut compiler);
//!
//! let request = Request {
//!     names: vec!["example".into()],
//! };
//! let state = NativeContextState::<()>::new(&scheme);
//!
//! // Each evaluation borrows the same request and state.
//! for _ in 0..2 {
//!     let context = RequestContext {
//!         request: &request,
//!         state: &state,
//!     };
//!     assert!(filter.execute(&context)?);
//! }
//! # Ok(())
//! # }
//! ```
//!
//! Initialization validation checks getter coverage, types, and optionality; it
//! does not call getters. Parsing and compilation do not invoke it automatically.
//!
//! The application controls the lifetime and cleanup of reusable state.
//! [`NativeContextState::clear`](crate::NativeContextState::clear) clears list contents
//! but retains user data; any compiler-specific cleanup remains the application's
//! responsibility. See [`values`] for supported storage and custom collection
//! interfaces, and [`wirefilter_fields!`](crate::wirefilter_fields) for getter forms.
//!
//! # Fields backed by `LhsValue`
//!
//! A context may also store [`LhsValue`](crate::LhsValue) fields whose types are
//! chosen when the scheme is built, including arbitrary array/map nesting.
//! [`LhsValueProvider`](crate::LhsValueProvider) reads these fields through the
//! same native binding interface. Its reader traverses and compares the existing
//! values without rebuilding containers. Function arguments borrow selected
//! values; flattening multiple selections still needs an output container.
//!
//! This example uses `ExecutionContext` as the field table. A downstream context
//! can implement its own table and evaluation state, then provide a getter with
//! the same return signature.
//!
//! ```
//! use wirefilter::{
//!     ContextFamily, DefaultCompiler, ExecutionContext, Field, FieldBindingError, FieldConsumer,
//!     FieldGetter, LhsValue, LhsValueProvider, SchemeBuilder, Type,
//! };
//!
//! struct Fields;
//! struct Getter;
//!
//! impl ContextFamily for Fields {
//!     type Context<'data> = ExecutionContext<'data>;
//!     type UserData = ();
//!
//!     fn bind<B: FieldConsumer<Self>>(
//!         field: Field,
//!         consumer: B,
//!     ) -> Result<B::Output, FieldBindingError> {
//!         consumer.native(field, Getter)
//!     }
//! }
//!
//! impl FieldGetter<Fields> for Getter {
//!     type Provider = LhsValueProvider;
//!
//!     fn get<'ctx, 'data: 'ctx>(
//!         &self,
//!         context: &'ctx ExecutionContext<'data>,
//!         field: &Field,
//!     ) -> Option<&'ctx LhsValue<'ctx>> {
//!         context.get_field_value(field.as_ref())
//!     }
//! }
//!
//! # fn main() -> Result<(), Box<dyn std::error::Error>> {
//! let mut builder = SchemeBuilder::new();
//! builder.add_field("port", Type::Int)?;
//! let scheme = builder.build();
//! let filter = scheme
//!     .parse("port eq 443")?
//!     .compile_with_compiler(&mut DefaultCompiler::<(), Fields>::new());
//! let mut context = ExecutionContext::new(&scheme);
//! context.set_field_value(scheme.get_field("port")?, 443i64)?;
//! assert!(filter.execute(&context)?);
//! # Ok(())
//! # }
//! ```
//!
//! The field's scheme type determines comparison and traversal during filter
//! compilation. Because a getter returning `&LhsValue` has no fixed logical type,
//! startup validation cannot check which variant it returns. The context must
//! check values against the scheme when inserting them, as `ExecutionContext`
//! does. The field macro still validates getter coverage and optionality.
//!
//! [`values::FieldValueType`] describes these scheme-typed field roots as well as
//! ordinary static [`values::ValueType`] implementations. Native collection
//! elements continue to require a static `ValueType`: for example, `Vec<i64>`
//! is supported, while a runtime-typed array uses `LhsValue::Array` rather than
//! `Vec<LhsValue>`.

